/**
 * Stamps, withdraws or checks a Codex integration certification record.
 *
 *   bun apps/server/scripts/stamp-integration-record.ts --integration codex-chrome|codex-computer
 *     [--evidence docs/computer-certification/<id>.json [--template <record.json>] [--reinstate]]
 *     [--withdraw <id> --reason <note>] [--check]
 *
 * Evidence from a live run (outside F5, on a clean commit) becomes a floor record: the
 * template's static identity, the exercised versions as `*Min` with no ceiling, and the
 * observed inventory, schemas and commit. The template is the newest non-withdrawn record
 * for the report's target (the one the live harness exercises), or `--template` (a record, or a Sky spike file's
 * `{ record }`). `--check` writes nothing and fails when a record cites evidence that
 * does not support it. Claude records are generated by generate-claude-chrome-descriptor.ts.
 */
import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import {
  evidenceMismatches,
  integrationTemplateRecord,
  type CodexChromeRecord,
  type CodexComputerRecord,
  type IntegrationEvidenceReport,
} from "@t3tools/shared/providerIntegrationCertification";
import {
  codexRecordFromEvidence,
  mergeIntegrationRecords,
} from "../src/provider/integrationRecordMerge";

type CodexRecord = CodexChromeRecord | CodexComputerRecord;
const root = resolve(import.meta.dirname, "../../..");
const argument = (name: string) => {
  const index = process.argv.indexOf(name);
  return index < 0 ? undefined : process.argv[index + 1];
};
const integration = argument("--integration");
if (integration !== "codex-chrome" && integration !== "codex-computer")
  throw new Error("Pass --integration codex-chrome or codex-computer.");
const outputPath = join(root, `packages/shared/src/certification/${integration}.generated.json`);
const current = await readFile(outputPath, "utf8");
const existing = JSON.parse(current) as CodexRecord[];

if (process.argv.includes("--check")) {
  const problems: string[] = [];
  for (const record of existing) {
    if (record.integration !== integration) problems.push(`${record.id}: wrong integration`);
    if (!record.evidenceId) continue;
    const path = join(root, "docs/computer-certification", `${record.evidenceId}.json`);
    if (!existsSync(path)) {
      problems.push(`${record.id}: cites missing ${record.evidenceId}`);
      continue;
    }
    const report = JSON.parse(await readFile(path, "utf8")) as IntegrationEvidenceReport;
    for (const problem of evidenceMismatches(record, report))
      problems.push(`${record.id}: ${problem}`);
  }
  if (problems.length) {
    console.error(problems.join("\n"));
    process.exitCode = 1;
  } else console.log(`${integration} records cite only supporting evidence.`);
} else {
  const withdrawId = argument("--withdraw");
  const withdrawReason = argument("--reason");
  if (withdrawId && !withdrawReason)
    throw new Error("--withdraw needs --reason, matching the CHANGELOG note.");
  const evidencePath = argument("--evidence");
  const report = evidencePath
    ? (JSON.parse(await readFile(resolve(evidencePath), "utf8")) as IntegrationEvidenceReport)
    : undefined;
  if (!report && !withdrawId) throw new Error("Pass --evidence <report> or --withdraw <id>.");
  let record: CodexRecord | undefined;
  if (report) {
    const templatePath = argument("--template");
    const template = templatePath
      ? ((parsed: CodexRecord | { record: CodexRecord }) =>
          "record" in parsed ? parsed.record : parsed)(
          JSON.parse(await readFile(resolve(templatePath), "utf8")),
        )
      : integrationTemplateRecord(existing, report.platform, report.arch);
    if (!template)
      throw new Error(
        `No ${integration} record for ${report.platform}-${report.arch}; pass --template.`,
      );
    record = codexRecordFromEvidence(template, report);
  }
  const next = mergeIntegrationRecords<CodexRecord>({
    existing,
    ...(record ? { record } : {}),
    ...(report ? { report } : {}),
    reinstate: process.argv.includes("--reinstate"),
    ...(withdrawId ? { withdraw: { id: withdrawId, reason: withdrawReason! } } : {}),
  });
  await writeFile(outputPath, `${JSON.stringify(next, null, 2)}\n`);
  // Leave the file as `bun fmt` would, so `fmt:check` stays clean.
  execFileSync(process.execPath, [join(root, "node_modules/oxfmt/bin/oxfmt"), outputPath], {
    cwd: root,
    stdio: "ignore",
  });
  if (record) console.log(`Stamped ${record.id} (evidence ${report!.evidenceId}).`);
  if (withdrawId) console.log(`Withdrew ${withdrawId}: ${withdrawReason}`);
}
