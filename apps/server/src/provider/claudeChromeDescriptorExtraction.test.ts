import { describe, expect, it } from "vitest";
import {
  CHUNK_MARKER,
  DescriptorAnchorError,
  bufferSource,
  extractClaudeChromeDescriptor,
  scanOffsets,
} from "./claudeChromeDescriptorExtraction";

const ORIGIN = "chrome-extension://fcoeoabgfenejglbffodgkkbkcdhcgfn/";
const banner = (version: string) =>
  `${CHUNK_MARKER}. Use of this software is subject to terms.\n// Version: ${version}\n`;

/** A minimal Bun single-file layout: bytecode with stale literals, then JS chunks. */
function binary(
  options: { extraDescription?: boolean; secondVersion?: string; noMarker?: boolean } = {},
) {
  const host = [
    banner("2.1.295"),
    'var hN="com.anthropic.claude_code_browser_extension",hF=`${hN}.json`;',
    'function mk(e){return{name:hN,description:"Claude Code Browser Extension Native Host",',
    `path:e,type:"stdio",allowed_origins:["${ORIGIN}"]}}`,
    options.extraDescription ? 'x={description:"Claude Code Browser Extension Native Host"};' : "",
    'let d=j(cfg(),"chrome"),f=w?k(d,"chrome-native-host.bat"):j(d,"chrome-native-host");',
    "let s=`#!/bin/sh\n# Chrome native host wrapper script\n# Generated by Claude Code - do not edit manually\nexec ${oo(a)}\n`;",
    'spawnArgs=[process.execPath,"--chrome-native-host"];',
    'if(process.argv[2]==="--chrome-native-host")runHost();',
    'if(process.argv[2]==="--claude-in-chrome-mcp")runMcp();',
    'var B={chrome:{name:"Google Chrome",macos:{appName:"Google Chrome",nativeMessagingPath:["Library","Application Support","Google","Chrome","NativeMessagingHosts"]}},',
    'brave:{name:"Brave",macos:{appName:"Brave Browser",nativeMessagingPath:["Library","Application Support","BraveSoftware","Brave-Browser","NativeMessagingHosts"]}}},',
    'O=["chrome","brave"];',
  ].join("");
  const mcp = [
    banner(options.secondVersion ?? "2.1.295"),
    'var cA="--claude-in-chrome-mcp",cN="claude-in-chrome";',
    'function cfg2(){return{[cN]:{type:"stdio",command:process.execPath,args:[cA],scope:"dynamic"}}}',
  ].join("");
  // Another dynamic server with the same config shape lives in its own chunk.
  const other = [
    banner("2.1.295"),
    'var zA="--computer-use-mcp";',
    'function cfg3(){return{cu:{type:"stdio",command:process.execPath,args:[zA],scope:"dynamic"}}}',
  ].join("");
  const stale = 'description:"Claude Code Browser Extension Native Host"' + "\0".repeat(64);
  return Buffer.from(
    (options.noMarker ? "" : stale) +
      (options.noMarker ? host.replace(CHUNK_MARKER, "") : host) +
      mcp +
      other,
    "latin1",
  );
}

describe("Claude in Chrome descriptor extraction", () => {
  it("extracts every field from the chunk region, ignoring stale bytecode copies", async () => {
    expect(await extractClaudeChromeDescriptor(bufferSource(binary()))).toEqual({
      cliVersion: "2.1.295",
      hostName: "com.anthropic.claude_code_browser_extension",
      hostDescription: "Claude Code Browser Extension Native Host",
      allowedOrigins: [ORIGIN],
      wrapperPath: ["chrome", "chrome-native-host"],
      wrapperHeader: [
        "#!/bin/sh",
        "# Chrome native host wrapper script",
        "# Generated by Claude Code - do not edit manually",
      ],
      nativeHostArgs: ["--chrome-native-host"],
      mcpServerName: "claude-in-chrome",
      mcpArgs: ["--claude-in-chrome-mcp"],
      browsers: [
        {
          id: "chrome",
          name: "Google Chrome",
          nativeMessagingPath: [
            "Library",
            "Application Support",
            "Google",
            "Chrome",
            "NativeMessagingHosts",
          ],
        },
        {
          id: "brave",
          name: "Brave",
          nativeMessagingPath: [
            "Library",
            "Application Support",
            "BraveSoftware",
            "Brave-Browser",
            "NativeMessagingHosts",
          ],
        },
      ],
    });
  });

  it.each([
    ["a duplicated anchor", { extraDescription: true }, "duplicated"],
    ["mixed chunk versions", { secondVersion: "2.1.296" }, "inconsistent"],
    ["a missing chunk marker", { noMarker: true }, "missing"],
  ])("fails with a typed error on %s", async (_name, options, problem) => {
    const error = await extractClaudeChromeDescriptor(bufferSource(binary(options))).catch(
      (cause: unknown) => cause,
    );
    expect(error).toBeInstanceOf(DescriptorAnchorError);
    expect((error as DescriptorAnchorError).problem).toBe(problem);
  });

  it("counts a match straddling a chunk boundary exactly once", async () => {
    const buffer = Buffer.from("....needle....needle", "latin1");
    for (const chunkSize of [3, 5, 7, 64])
      expect(
        (await scanOffsets(bufferSource(buffer), ["needle"], 0, chunkSize)).get("needle"),
      ).toEqual([4, 14]);
  });
});
