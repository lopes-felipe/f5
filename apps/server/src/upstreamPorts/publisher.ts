/**
 * Publishes recorded ops to the rolling ledger PR. One step runs at a time per
 * project; the service schedules steps (after ops, after runs, every 15
 * minutes, and on `resolvePublication`). Pauses never affect the view.
 *
 * @module upstreamPorts/publisher
 */
import type { UpstreamPublicationPauseReason } from "@t3tools/contracts";
import {
  isLedgerStatePath,
  opEffectPresent,
  serializeLedgerFiles,
  type UpstreamLedger,
} from "@t3tools/shared/upstreamPorts";
import { Effect, Schema } from "effect";

import { GitCommandError } from "../git/Errors.ts";
import type { UpstreamGit } from "./git.ts";
import { UpstreamSigningError } from "./git.ts";
import type {
  GitHubRepoRef,
  LedgerPullRequest,
  UpstreamGitHub,
  UpstreamGitHubError,
} from "./github.ts";
import type { OpRecord, PublicationRecord, UpstreamStore, UpstreamStoreError } from "./store.ts";
import { buildView, countStates, type DerivedRow, type LedgerView } from "./view.ts";

export const PUBLISH_DEBOUNCE_MS = 10_000;
export const PUBLISH_INTERVAL_MS = 15 * 60_000;
export const BASE_FETCH_MIN_INTERVAL_MS = 2 * 60_000;
export const PUSH_BACKOFF_MS = [30_000, 120_000, 600_000] as const;

export function pushBackoffMs(attempts: number): number {
  return PUSH_BACKOFF_MS[Math.min(Math.max(attempts, 1), PUSH_BACKOFF_MS.length) - 1]!;
}

const pad = (value: number) => String(value).padStart(2, "0");

export function ledgerBranchName(now: Date): string {
  return `f5/upstream-ledger-${now.getFullYear()}${pad(now.getMonth() + 1)}${pad(now.getDate())}-${pad(now.getHours())}${pad(now.getMinutes())}`;
}

export function ledgerPrTitle(today: string): string {
  return `Track upstream t3code changes (${today})`;
}

export function ledgerPrBody(input: {
  readonly repository: string;
  readonly ledger: UpstreamLedger;
  readonly base: UpstreamLedger;
  readonly rows: ReadonlyArray<DerivedRow>;
}): string {
  const baseIntervals = new Set(input.base.intervals.map((file) => file.interval));
  const added = input.ledger.intervals.filter((file) => !baseIntervals.has(file.interval));
  const target = input.ledger.intervals.at(-1)?.targetSha.slice(0, 12) ?? "the archive target";
  const commits = added.reduce((sum, file) => sum + file.count, 0);
  const counts = countStates(input.rows);
  const auto = input.rows.filter(
    (row) =>
      row.state === "skipped" && (row.topic.decidedBy === "rule" || row.topic.decidedBy === "llm"),
  ).length;
  return [
    "## What",
    `Tracks ${input.repository} through ${target} and records upstream triage decisions made in F5.`,
    "",
    "## Why",
    "Keeps the upstream ledger current so each upstream change is reviewed once and ports reference stable topic ids.",
    "",
    "## How",
    `${added.length} interval(s) cover ${commits} upstream commits. Topics: ${counts.inbox} to review, ${counts.ready + counts["in-progress"]} to port, ${counts.skipped} skipped (${auto} automatically), ${counts.done} done. Generated by F5 and validated by \`upstream-ports:check\`. Automatic skips come from upstream commit and PR text; review them in F5 before merging.`,
    "",
  ].join("\n");
}

/** Commit message for the ops published in one commit. */
export function ledgerCommitMessage(
  ops: ReadonlyArray<OpRecord>,
  rows: ReadonlyArray<DerivedRow>,
): string {
  const intervals = ops.flatMap((record) => (record.op.kind === "interval" ? [record.op] : []));
  if (intervals.length > 0) {
    const last = intervals.at(-1)!;
    const commits = intervals.reduce((sum, op) => sum + op.file.count, 0);
    const inbox = rows.filter((row) => row.state === "inbox").length;
    return `Track upstream through ${last.file.targetSha.slice(0, 12)} (${commits} commits, ${inbox} to review)`;
  }
  const legacy = ops.filter((record) => record.op.kind === "legacy");
  if (legacy.length > 0 && legacy.length === ops.length) {
    const commits = legacy.reduce(
      (sum, record) => sum + (record.op.kind === "legacy" ? record.op.file.count : 0),
      0,
    );
    return `Triage legacy upstream backlog (${commits} commits)`;
  }
  const tally = { port: 0, skip: 0, watch: 0, declined: 0, reopened: 0 };
  for (const record of ops) {
    if (record.op.kind !== "decision") continue;
    const status = record.op.fields.status;
    if (status === "inbox") tally.reopened += 1;
    // Equivalent topics are not ported here; they count with skips.
    else if (status === "skip" || status === "equivalent") tally.skip += 1;
    else tally[status] += 1;
  }
  return `Record upstream triage: ${tally.port} port, ${tally.skip} skip, ${tally.watch} watch, ${tally.declined} declined, ${tally.reopened} reopened`;
}

/** Repo-relative files whose content must change on the branch so it matches the view. */
export function ledgerFileChanges(input: {
  readonly ledgerDir: string;
  readonly view: UpstreamLedger;
  readonly current: ReadonlyMap<string, string>;
}): Map<string, string | null> {
  const prefix = `${input.ledgerDir}/`;
  const wanted = new Map(
    [...serializeLedgerFiles(input.view)].map(([relative, text]) => [`${prefix}${relative}`, text]),
  );
  const changes = new Map<string, string | null>();
  for (const [file, text] of wanted) if (input.current.get(file) !== text) changes.set(file, text);
  for (const file of input.current.keys())
    if (
      file.startsWith(prefix) &&
      isLedgerStatePath(file.slice(prefix.length)) &&
      !wanted.has(file)
    )
      changes.set(file, null);
  return changes;
}

/** Ops whose effect is already on `origin/<base>`, compared by content. */
export function mergedOpIds(base: UpstreamLedger, ops: ReadonlyArray<OpRecord>): string[] {
  return ops.filter((record) => opEffectPresent(base, record.op)).map((record) => record.opId);
}

/** The pause a push failure needs, or null when retrying later may succeed. */
export function unparsedLedgerMessage(baseBranch: string, files: ReadonlyArray<string>): string {
  return `Fix the ledger files on origin/${baseBranch} that F5 cannot read: ${files.slice(0, 3).join(", ")}${files.length > 3 ? ", …" : ""}.`;
}

export function classifyPushFailure(detail: string): UpstreamPublicationPauseReason | null {
  if (
    /non-fast-forward|\[rejected\]|fetch first|stale info|protected branch|pre-receive hook declined/iu.test(
      detail,
    )
  )
    return "push-rejected";
  if (
    /authentication failed|permission denied|could not read (?:username|password)|access denied|invalid credentials|requested url returned error: 40[13]|denied to /iu.test(
      detail,
    )
  )
    return "auth";
  return null;
}

export interface PublisherContext {
  readonly projectId: string;
  readonly cwd: string;
  readonly repository: string;
  readonly remote: string;
  readonly baseBranch: string;
  readonly ledgerDir: string;
  readonly githubRepo: GitHubRepoRef | null;
  readonly git: UpstreamGit;
  readonly github: UpstreamGitHub | null;
  readonly store: UpstreamStore;
  readonly now: () => Date;
  readonly today: () => string;
  /**
   * Fetches `origin/<base>` and returns its ledger. The caller throttles
   * fetches unless `refresh` is set.
   */
  readonly loadBase: (options: { readonly refresh: boolean }) => Effect.Effect<
    {
      readonly baseSha: string | null;
      readonly ledger: UpstreamLedger;
      /** Ledger files that failed to parse; publishing would drop their content. */
      readonly unparsed: ReadonlyArray<string>;
    },
    Error
  >;
  readonly deriveRows: (view: LedgerView) => Effect.Effect<DerivedRow[]>;
  readonly isWriter: Effect.Effect<boolean>;
  readonly resolveBranchName: (name: string) => Effect.Effect<string, Error>;
}

export type PublishOutcome =
  | { readonly kind: "idle" }
  | { readonly kind: "paused"; readonly reason: UpstreamPublicationPauseReason }
  | { readonly kind: "retry-later"; readonly delayMs: number }
  | { readonly kind: "published"; readonly again: boolean };

const describe = (error: unknown) =>
  Schema.is(GitCommandError)(error)
    ? error.detail
    : error instanceof Error
      ? error.message
      : String(error);

/**
 * One publication step (plan §4.3 steps 1-9). `force` is set by
 * `resolvePublication` retry/republish and clears an existing pause first.
 */
export function publishStep(
  context: PublisherContext,
  options: { readonly force?: "retry" | "republish" } = {},
): Effect.Effect<PublishOutcome, UpstreamStoreError> {
  const { store, projectId } = context;
  return Effect.gen(function* () {
    let publication = yield* store.getPublication(projectId);
    const save = (patch: Partial<PublicationRecord>) =>
      Effect.gen(function* () {
        publication = { ...publication, ...patch, lastAttemptAt: context.now().toISOString() };
        yield* store.savePublication(publication);
      });
    const pause = (reason: UpstreamPublicationPauseReason, detail: string | null) =>
      save({ phase: "idle", pausedReason: reason, lastError: detail, nextAttemptAt: null }).pipe(
        Effect.as<PublishOutcome>({ kind: "paused", reason }),
      );
    const retryLater = (detail: string) =>
      Effect.gen(function* () {
        const attempts = publication.attempts + 1;
        const delayMs = pushBackoffMs(attempts);
        yield* save({
          phase: "idle",
          attempts,
          lastError: detail,
          nextAttemptAt: new Date(context.now().getTime() + delayMs).toISOString(),
        });
        return { kind: "retry-later", delayMs } satisfies PublishOutcome;
      });
    // Transient GitHub failures retry with backoff; anything else needs the user.
    const githubFailure = (error: UpstreamGitHubError) =>
      error.transient ? retryLater(error.detail) : pause("auth", error.detail);

    if (options.force === "republish") {
      yield* save({
        branch: null,
        prNumber: null,
        prUrl: null,
        prState: null,
        lastCommitSha: null,
        lastPushedSha: null,
        pausedReason: null,
        lastError: null,
        attempts: 0,
      });
    } else if (options.force === "retry") {
      yield* save({ pausedReason: null, lastError: null, attempts: 0, nextAttemptAt: null });
    } else if (publication.pausedReason !== null) {
      return { kind: "paused", reason: publication.pausedReason } satisfies PublishOutcome;
    }

    if (!(yield* context.isWriter))
      return yield* pause("writer-lost", "Another F5 profile manages this repository.");

    // 1. Fetch origin/<base> and run merged detection. A merged ledger PR
    // must be on the base before planning, or its ops would be replayed.
    const refresh = options.force !== undefined || publication.prState === "merged";
    const base = yield* context.loadBase({ refresh }).pipe(Effect.result);
    if (base._tag === "Failure") return yield* retryLater(describe(base.failure));
    const openBefore = yield* store.listOpenOps(projectId);
    const merged = mergedOpIds(base.success.ledger, openBefore);
    if (merged.length) yield* store.setOpStates(merged, "merged", context.now().toISOString());
    const open = openBefore.filter((record) => !merged.includes(record.opId));

    // 2. Nothing left to publish.
    if (open.length === 0) {
      yield* save({ phase: "idle", lastError: null, attempts: 0, nextAttemptAt: null });
      return { kind: "idle" } satisfies PublishOutcome;
    }
    const baseSha = base.success.baseSha;
    if (baseSha === null)
      return yield* pause("conflict", `origin/${context.baseBranch} is missing.`);
    if (base.success.unparsed.length > 0)
      return yield* pause(
        "conflict",
        unparsedLedgerMessage(context.baseBranch, base.success.unparsed),
      );

    const view = buildView(baseSha, base.success.ledger, open);
    if (view.conflicts.length)
      return yield* pause("conflict", view.conflicts.slice(0, 3).join("; "));
    const rows = yield* context.deriveRows(view);

    if (!context.github) return yield* pause("auth", "GitHub is unavailable in this F5 build.");
    if (!context.githubRepo)
      return yield* pause("auth", "The origin remote is not a GitHub repository.");
    const github = context.github;
    const repo = context.githubRepo;
    const signedIn = yield* github.available(context.cwd).pipe(Effect.result);
    if (signedIn._tag === "Failure") return yield* githubFailure(signedIn.failure);
    if (!signedIn.success)
      return yield* pause(
        "auth",
        "GitHub is not connected. Connect it in Settings > Integrations.",
      );

    // 3-5. PR state and branch selection.
    let pr: LedgerPullRequest | null = null;
    if (publication.prNumber !== null) {
      const found = yield* github
        .findPullRequest({ cwd: context.cwd, repo, number: publication.prNumber })
        .pipe(Effect.result);
      if (found._tag === "Failure") return yield* githubFailure(found.failure);
      pr = found.success;
      if (pr?.state === "closed")
        return yield* pause("closed-pr", `Ledger PR #${pr.number} was closed without merging.`);
      if (pr?.state === "merged" && !refresh) {
        // Replan against a freshly fetched base that includes the merge; the
        // saved state makes the next step refresh, so this recurses once.
        yield* save({ prState: "merged" });
        return yield* publishStep(context, options);
      }
    }
    let branch = publication.branch;
    let tip: string | null = branch
      ? yield* context.git
          .revParse(context.cwd, `refs/heads/${branch}`)
          .pipe(Effect.orElseSucceed(() => null))
      : null;
    if (pr?.state === "merged" || branch === null || tip === null) {
      // A merged PR's branch is done; drop its local ref (the remote keeps it).
      if (pr?.state === "merged" && branch !== null && tip !== null)
        yield* context.git.deleteBranch(context.cwd, branch, tip).pipe(
          Effect.catch((error) =>
            Effect.logWarning("upstreamPorts.publish.deleteBranch.failed", {
              detail: describe(error),
            }),
          ),
        );
      const fresh = yield* context
        .resolveBranchName(ledgerBranchName(context.now()))
        .pipe(Effect.result);
      if (fresh._tag === "Failure") return yield* pause("conflict", describe(fresh.failure));
      branch = fresh.success;
      tip = null;
      pr = null;
      yield* save({
        branch,
        prNumber: null,
        prUrl: null,
        prState: null,
        lastCommitSha: null,
        lastPushedSha: null,
      });
    }

    // 6. Commit the files that differ from the branch tip.
    yield* save({ phase: "committing" });
    const parent = tip ?? baseSha;
    const current = yield* context.git
      .readFilesAtRef({ cwd: context.cwd, ref: parent, pathPrefixes: [context.ledgerDir] })
      .pipe(Effect.result);
    if (current._tag === "Failure") return yield* pause("conflict", describe(current.failure));
    const changes = ledgerFileChanges({
      ledgerDir: context.ledgerDir,
      view: view.ledger,
      current: current.success,
    });
    let head = tip;
    if (changes.size > 0 || tip === null) {
      const sign = yield* context.git
        .signingEnabled(context.cwd)
        .pipe(Effect.orElseSucceed(() => false));
      const committed = yield* context.git
        .commitFilesToBranch({
          cwd: context.cwd,
          branch: branch!,
          parent,
          expectedTip: tip,
          files: changes,
          message: ledgerCommitMessage(open, rows),
          sign,
        })
        .pipe(Effect.result);
      if (committed._tag === "Failure") {
        const error = committed.failure;
        if (error instanceof UpstreamSigningError || /timed out/u.test(describe(error)))
          return yield* pause("signing", describe(error));
        return yield* pause("conflict", describe(error));
      }
      head = committed.success;
      yield* save({ lastCommitSha: head });
    }

    // 7. Push.
    if (publication.lastPushedSha !== head) {
      yield* save({ phase: "pushing" });
      const pushed = yield* context.git.push(context.cwd, "origin", branch!).pipe(Effect.result);
      if (pushed._tag === "Failure") {
        const detail = describe(pushed.failure);
        const reason = classifyPushFailure(detail);
        if (reason !== null && publication.attempts + 1 > PUSH_BACKOFF_MS.length)
          return yield* pause(reason, detail);
        return yield* retryLater(detail);
      }
      yield* save({ lastPushedSha: head, attempts: 0, lastError: null, nextAttemptAt: null });
    }

    // 8. Open the PR, or refresh its body.
    const body = ledgerPrBody({
      repository: context.repository,
      ledger: view.ledger,
      base: base.success.ledger,
      rows,
    });
    if (pr === null) {
      yield* save({ phase: "opening-pr" });
      const existing = yield* github
        .findPullRequestForBranch({ cwd: context.cwd, repo, branch: branch! })
        .pipe(Effect.result);
      if (existing._tag === "Failure") return yield* githubFailure(existing.failure);
      const created =
        existing.success && existing.success.state === "open"
          ? Effect.succeed(existing.success)
          : github.createPullRequest({
              cwd: context.cwd,
              repo,
              base: context.baseBranch,
              head: branch!,
              title: ledgerPrTitle(context.today()),
              body,
            });
      const result = yield* created.pipe(Effect.result);
      if (result._tag === "Failure") return yield* githubFailure(result.failure);
      pr = result.success;
    } else {
      yield* github.updatePullRequestBody({ cwd: context.cwd, repo, number: pr.number, body }).pipe(
        Effect.catch((error) =>
          Effect.logWarning("upstreamPorts.publish.updateBody.failed", {
            detail: describe(error),
          }),
        ),
      );
    }
    yield* save({
      phase: "idle",
      prNumber: pr.number,
      prUrl: pr.url,
      prState: pr.state,
      pausedReason: null,
      attempts: 0,
      lastError: null,
      nextAttemptAt: null,
    });

    // 9. Re-read: a PR merged between the check and the push leaves its
    // leftover ops non-merged; the next step replays them on a fresh branch.
    const reread = yield* github
      .findPullRequest({ cwd: context.cwd, repo, number: pr.number })
      .pipe(Effect.orElseSucceed(() => pr));
    if (reread && reread.state !== pr.state) yield* save({ prState: reread.state });
    return { kind: "published", again: reread?.state === "merged" } satisfies PublishOutcome;
  });
}
